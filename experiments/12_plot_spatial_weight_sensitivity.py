import os
"""
12_plot_spatial_weight_sensitivity.py
=====================================

Reads the two weight-sensitivity summary CSVs already generated by
11_spatial_fusion_weight_sensitivity.py and creates paper-ready figures.

No model, score, or label is recomputed.

Expected project structure
--------------------------
08_Weight_Sensitivity_Results_Seed_42/
    Weight_Sensitivity_Summary.csv
    Weight_Sensitivity_Summary_Additional_Weights.csv

Outputs
-------
08_Weight_Sensitivity_Results_Seed_42/Figures/
    Weight_Sensitivity_Full_Budget_Mean_DR.png
    Weight_Sensitivity_Pure_Budget_Mean_DR.png
    Weight_Sensitivity_Top2_Mean_DR.png
    Weight_Sensitivity_Top2_Hard_Scenarios.png
    Weight_Sensitivity_Clean_Jaccard.png
    Weight_Sensitivity_Full_Top2_All_Scenarios.png
    Weight_Sensitivity_Pure_Top2_All_Scenarios.png

Also writes:
    Weight_Sensitivity_Paper_Summary.csv

Notes
-----
- beta is the spatial-score weight and alpha = 1-beta.
- Mean DR curves average over all five corruption scenarios and all
  three injection ratios unless explicitly stated otherwise.
- Scenario-wise top-2% curves average over the three injection ratios.
- Clean Jaccard is measured against the verified alpha=0.75, beta=0.25
  clean top-2% anomaly mask stored in the sensitivity summary.
"""

from pathlib import Path
import numpy as np
import pandas as pd
import matplotlib.pyplot as plt


# ============================================================================
# 1. PATHS
# ============================================================================

ROOT_DIR = Path(os.environ.get("GIS_ANOMALY_PROJECT_ROOT", Path.cwd())).resolve()

RESULT_DIR = ROOT_DIR / "08_Weight_Sensitivity_Results_Seed_42"

CSV_1 = RESULT_DIR / "Weight_Sensitivity_Summary.csv"
CSV_2 = RESULT_DIR / "Weight_Sensitivity_Summary_Additional_Weights.csv"

FIGURE_DIR = RESULT_DIR / "Figures"
FIGURE_DIR.mkdir(parents=True, exist_ok=True)

SELECTED_BETA = 0.60
REFERENCE_BETA = 0.25

EXPECTED_BETAS = [
    0.00, 0.10, 0.20, 0.25, 0.30, 0.40,
    0.50, 0.60, 0.70, 0.80, 0.90, 1.00,
]

BUDGET_ORDER = [0.10, 0.25, 0.50, 1.00, 2.00]

SCENARIO_ORDER = [
    "Extreme",
    "Strong noise",
    "Moderate noise",
    "Mild noise",
    "Cross-feature inconsistency",
]

HARD_SCENARIOS = [
    "Mild noise",
    "Cross-feature inconsistency",
]


# ============================================================================
# 2. LOAD AND VALIDATE
# ============================================================================

for path in [CSV_1, CSV_2]:
    if not path.exists():
        raise FileNotFoundError(path)

df = pd.concat(
    [
        pd.read_csv(CSV_1),
        pd.read_csv(CSV_2),
    ],
    ignore_index=True,
)

# Remove an accidental duplicate row if the two files ever overlap.
dedup_cols = [
    "Record_Type",
    "Alpha",
    "Beta",
    "Variant",
    "Injection_Ratio",
    "Scenario",
    "Budget_Percent",
]
df = df.drop_duplicates(
    subset=dedup_cols,
    keep="last",
).reset_index(drop=True)

injected = df[df["Record_Type"] == "Injected"].copy()
clean = df[df["Record_Type"] == "Clean"].copy()

observed_betas = sorted(
    injected["Beta"].dropna().unique().tolist()
)

if len(observed_betas) != len(EXPECTED_BETAS):
    raise ValueError(
        f"Expected {len(EXPECTED_BETAS)} beta settings; "
        f"found {len(observed_betas)}: {observed_betas}"
    )

if not np.allclose(
    observed_betas,
    EXPECTED_BETAS,
    atol=1e-12,
):
    raise ValueError(
        "Unexpected beta grid:\n"
        f"{observed_betas}"
    )

expected_injected_rows = (
    len(EXPECTED_BETAS)
    * 2       # Full/Pure
    * 3       # injection ratios
    * 5       # scenarios
    * 5       # budgets
)

if len(injected) != expected_injected_rows:
    raise ValueError(
        f"Expected {expected_injected_rows} injected rows; "
        f"found {len(injected)}."
    )

print("Weight-sensitivity input validation passed.")
print("Injected rows:", len(injected))
print("Clean rows:", len(clean))
print("Beta settings:", observed_betas)


# ============================================================================
# 3. AGGREGATED DATA
# ============================================================================

# Mean detection rate over all five scenarios and all three injection ratios,
# separately for each budget.
budget_mean = (
    injected
    .groupby(
        ["Beta", "Variant", "Budget_Percent"],
        as_index=False,
    )["Detection_Rate_Percent"]
    .mean()
)

# Principal top-2% mean over all five scenarios and all three ratios.
top2_mean = (
    injected[
        np.isclose(
            injected["Budget_Percent"],
            2.0,
        )
    ]
    .groupby(
        ["Beta", "Variant"],
        as_index=False,
    )["Detection_Rate_Percent"]
    .mean()
)

# Scenario-specific top-2% result, averaged over the three injection ratios.
top2_scenario = (
    injected[
        np.isclose(
            injected["Budget_Percent"],
            2.0,
        )
    ]
    .groupby(
        ["Beta", "Variant", "Scenario"],
        as_index=False,
    )["Detection_Rate_Percent"]
    .mean()
)

# Clean top-2% Jaccard relative to the verified 0.75/0.25 clean masks.
clean_jaccard = (
    clean[
        [
            "Beta",
            "Variant",
            "Jaccard_vs_Reference_075",
            "Full_Pure_Clean_Jaccard",
        ]
    ]
    .drop_duplicates()
    .sort_values(["Beta", "Variant"])
)


# ============================================================================
# 4. COMMON PLOT HELPERS
# ============================================================================

def finalize_axis(ax, ylabel, title):
    ax.set_xlabel(r"Spatial weight $\beta$ ($\alpha=1-\beta$)")
    ax.set_ylabel(ylabel)
    ax.set_title(title)
    ax.set_xticks(EXPECTED_BETAS)
    ax.grid(True, alpha=0.25)
    ax.legend()
    ax.axvline(
        SELECTED_BETA,
        linestyle="--",
        linewidth=1.2,
        label=r"Best common top-2\% sensitivity region ($\beta=0.60$)",
    )
    ax.axvline(
        REFERENCE_BETA,
        linestyle=":",
        linewidth=1.2,
        label=r"Main configuration ($\beta=0.25$)"
    )


def save_figure(fig, filename):
    path = FIGURE_DIR / filename
    fig.tight_layout()
    fig.savefig(
        path,
        dpi=300,
        bbox_inches="tight",
    )
    plt.close(fig)
    print("Saved:", path)


# ============================================================================
# 5. FIGURE: MEAN DR BY BUDGET -- FULL
# ============================================================================

fig, ax = plt.subplots(figsize=(8.2, 5.4))

for budget in BUDGET_ORDER:
    sub = budget_mean[
        (budget_mean["Variant"] == "Full")
        & np.isclose(
            budget_mean["Budget_Percent"],
            budget,
        )
    ].sort_values("Beta")

    ax.plot(
        sub["Beta"],
        sub["Detection_Rate_Percent"],
        marker="o",
        label=f"Top {budget:g}%",
    )

finalize_axis(
    ax,
    "Mean injected-anomaly detection rate (%)",
    "Full: spatial-fusion weight sensitivity across selection budgets",
)

# Re-create legend after vertical-line labels have been added.
ax.legend()

save_figure(
    fig,
    "Weight_Sensitivity_Full_Budget_Mean_DR.png",
)


# ============================================================================
# 6. FIGURE: MEAN DR BY BUDGET -- PURE
# ============================================================================

fig, ax = plt.subplots(figsize=(8.2, 5.4))

for budget in BUDGET_ORDER:
    sub = budget_mean[
        (budget_mean["Variant"] == "Pure")
        & np.isclose(
            budget_mean["Budget_Percent"],
            budget,
        )
    ].sort_values("Beta")

    ax.plot(
        sub["Beta"],
        sub["Detection_Rate_Percent"],
        marker="o",
        label=f"Top {budget:g}%",
    )

finalize_axis(
    ax,
    "Mean injected-anomaly detection rate (%)",
    "Pure: spatial-fusion weight sensitivity across selection budgets",
)
ax.legend()

save_figure(
    fig,
    "Weight_Sensitivity_Pure_Budget_Mean_DR.png",
)


# ============================================================================
# 7. FIGURE: PRINCIPAL TOP-2% MEAN DR -- FULL VS PURE
# ============================================================================

fig, ax = plt.subplots(figsize=(8.0, 5.2))

for variant in ["Full", "Pure"]:
    sub = top2_mean[
        top2_mean["Variant"] == variant
    ].sort_values("Beta")

    ax.plot(
        sub["Beta"],
        sub["Detection_Rate_Percent"],
        marker="o",
        label=variant,
    )

finalize_axis(
    ax,
    "Mean top-2% detection rate (%)",
    "Principal operating-point sensitivity",
)
ax.legend()

save_figure(
    fig,
    "Weight_Sensitivity_Top2_Mean_DR.png",
)


# ============================================================================
# 8. FIGURE: HARD SCENARIOS AT TOP-2%
# ============================================================================

fig, ax = plt.subplots(figsize=(8.4, 5.4))

for variant in ["Full", "Pure"]:
    for scenario in HARD_SCENARIOS:
        sub = top2_scenario[
            (top2_scenario["Variant"] == variant)
            & (
                top2_scenario["Scenario"]
                == scenario
            )
        ].sort_values("Beta")

        ax.plot(
            sub["Beta"],
            sub["Detection_Rate_Percent"],
            marker="o",
            label=f"{variant} -- {scenario}",
        )

finalize_axis(
    ax,
    "Mean top-2% detection rate (%)",
    "Sensitivity of the most discriminative corruption scenarios",
)
ax.legend()

save_figure(
    fig,
    "Weight_Sensitivity_Top2_Hard_Scenarios.png",
)


# ============================================================================
# 9. FIGURE: CLEAN-SELECTION JACCARD SENSITIVITY
# ============================================================================

fig, ax = plt.subplots(figsize=(8.0, 5.2))

for variant in ["Full", "Pure"]:
    sub = clean_jaccard[
        clean_jaccard["Variant"] == variant
    ].sort_values("Beta")

    ax.plot(
        sub["Beta"],
        sub["Jaccard_vs_Reference_075"],
        marker="o",
        label=f"{variant} vs. previous 0.75/0.25 mask",
    )

# Full--Pure overlap is the same in the Full and Pure clean rows.
overlap = (
    clean_jaccard[
        clean_jaccard["Variant"] == "Full"
    ]
    .sort_values("Beta")
)

ax.plot(
    overlap["Beta"],
    overlap["Full_Pure_Clean_Jaccard"],
    marker="o",
    label="Full--Pure clean-set overlap",
)

finalize_axis(
    ax,
    "Jaccard similarity",
    "Sensitivity of clean top-2% anomaly selections",
)
ax.set_ylim(0.0, 1.05)
ax.legend()

save_figure(
    fig,
    "Weight_Sensitivity_Clean_Jaccard.png",
)


# ============================================================================
# 10. OPTIONAL FIGURES: ALL FIVE SCENARIOS AT TOP-2%
# ============================================================================

for variant in ["Full", "Pure"]:
    fig, ax = plt.subplots(figsize=(8.4, 5.4))

    for scenario in SCENARIO_ORDER:
        sub = top2_scenario[
            (top2_scenario["Variant"] == variant)
            & (
                top2_scenario["Scenario"]
                == scenario
            )
        ].sort_values("Beta")

        ax.plot(
            sub["Beta"],
            sub["Detection_Rate_Percent"],
            marker="o",
            label=scenario,
        )

    finalize_axis(
        ax,
        "Mean top-2% detection rate (%)",
        f"{variant}: scenario-wise spatial-weight sensitivity",
    )
    ax.legend()

    save_figure(
        fig,
        f"Weight_Sensitivity_{variant}_Top2_All_Scenarios.png",
    )


# ============================================================================
# 11. PAPER SUMMARY TABLE
# ============================================================================

summary_rows = []

for beta in EXPECTED_BETAS:
    row = {
        "Alpha": 1.0 - beta,
        "Beta": beta,
    }

    for variant in ["Full", "Pure"]:
        prefix = "Full" if variant == "Full" else "Pure"

        mean_value = top2_mean[
            (np.isclose(top2_mean["Beta"], beta))
            & (top2_mean["Variant"] == variant)
        ]["Detection_Rate_Percent"].iloc[0]

        mild_value = top2_scenario[
            (np.isclose(top2_scenario["Beta"], beta))
            & (top2_scenario["Variant"] == variant)
            & (top2_scenario["Scenario"] == "Mild noise")
        ]["Detection_Rate_Percent"].iloc[0]

        cross_value = top2_scenario[
            (np.isclose(top2_scenario["Beta"], beta))
            & (top2_scenario["Variant"] == variant)
            & (
                top2_scenario["Scenario"]
                == "Cross-feature inconsistency"
            )
        ]["Detection_Rate_Percent"].iloc[0]

        jac_value = clean_jaccard[
            (np.isclose(clean_jaccard["Beta"], beta))
            & (clean_jaccard["Variant"] == variant)
        ]["Jaccard_vs_Reference_075"].iloc[0]

        row[f"{prefix}_Mean_Top2_DR"] = mean_value
        row[f"{prefix}_Mild_Top2_DR"] = mild_value
        row[f"{prefix}_Cross_Top2_DR"] = cross_value
        row[f"{prefix}_Clean_Jaccard"] = jac_value

    summary_rows.append(row)

summary_df = pd.DataFrame(summary_rows)

summary_path = (
    RESULT_DIR
    / "Weight_Sensitivity_Paper_Summary.csv"
)

summary_df.to_csv(
    summary_path,
    index=False,
)

print("Saved:", summary_path)
print("\nCompleted successfully.")
